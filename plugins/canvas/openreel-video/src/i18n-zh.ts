// ─────────────────────────────────────────────────────────────────────────────
// 组合串翻译（分词替换）
//
// OpenReel 有大量「运行期拼接」出来的界面文案（例如 `${n} clips`、`Add ${name}`、
// `Exported ${n} files`），整串匹配无法覆盖。这里把词典里的词/短语在更长的文本中
// 就地替换 —— 依然只作用于「已渲染的文本节点」，不触碰任何逻辑值。
//
// 边界规则：
//   · 短语（含空格）按常规单词边界匹配；
//   · 单词额外禁止右侧紧跟 . _ - 与字母数字，避免把 "Color.mp4"、"my_clip" 这类
//     素材名/文件名误译。
// ─────────────────────────────────────────────────────────────────────────────
const escapeRe = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** 参与分词替换的词典键（跳过「译名与原文相同」的项）。 */
const PHRASE_KEYS = Object.keys(ZH_DICT)
  .filter((key) => key.length >= 2 && ZH_DICT[key] !== key)
  .sort((a, b) => b.length - a.length);

const PHRASE_MULTI = PHRASE_KEYS.filter((key) => /\s/.test(key)).map(escapeRe);
const PHRASE_SINGLE = PHRASE_KEYS.filter((key) => !/\s/.test(key)).map((key) => `${escapeRe(key)}(?![A-Za-z0-9._-])`);

/** 单个大正则，一次扫描完成全部替换（按长度降序，保证最长优先匹配）。 */
const PHRASE_RE = PHRASE_MULTI.length + PHRASE_SINGLE.length
  ? new RegExp(`(^|[^A-Za-z0-9._-])(${[...PHRASE_MULTI, ...PHRASE_SINGLE].join("|")})(?=[^A-Za-z0-9]|$)`, "g")
  : null;

/** 形如 "clip.mp4" / "photo.png" 的素材名不参与分词替换，避免改坏用户文件名。 */
const LOOKS_LIKE_FILENAME = /\.[A-Za-z0-9]{2,5}(?:\s|$)/;

const composedCache = new Map<string, string>();

export function composeTranslate(text: string): string | null {
  if (!PHRASE_RE || text.length < 3 || text.length > 400) return null;
  if (!/[A-Za-z]/.test(text)) return null;
  if (LOOKS_LIKE_FILENAME.test(text)) return null;
  const cached = composedCache.get(text);
  if (cached !== undefined) return cached === text ? null : cached;
  PHRASE_RE.lastIndex = 0;
  const next = text.replace(PHRASE_RE, (_m, prefix: string, word: string) => `${prefix}${ZH_DICT[word] ?? word}`);
  if (composedCache.size < 4000) composedCache.set(text, next);
  return next === text ? null : next;
}

/** 先整串精确匹配，再退回分词替换。 */
function localize(text: string): string | null {
  const exact = ZH_DICT[text];
  if (exact && exact !== text) return exact;
  return composeTranslate(text);
}

function shouldSkip(node: Node): boolean {
  let el: Element | null = node.parentElement;
  while (el) {
    if (SKIP_TAGS.has(el.tagName)) return true;
    if ((el as HTMLElement).isContentEditable === true) return true;
    const ds = (el as HTMLElement).dataset;
    if (ds && ds.i18nSkip !== undefined) return true;
    el = el.parentElement;
  }
  return false;
}

function translateTextNode(node: Text): boolean {
  const raw = node.nodeValue;
  if (!raw) return false;
  const key = raw.trim();
  if (!key) return false;
  if (shouldSkip(node)) return false;
  const zh = localize(key);
  if (!zh) return false;
  const idx = raw.indexOf(key);
  if (idx < 0) return false;
  node.nodeValue = raw.slice(0, idx) + zh + raw.slice(idx + key.length);
  return true;
}

/** `<input type="button|submit|reset">` 的 value 是纯展示文本，可安全翻译。 */
function translateInputValue(el: Element): boolean {
  if (el.tagName !== "INPUT") return false;
  const type = (el as HTMLInputElement).type;
  if (type !== "button" && type !== "submit" && type !== "reset") return false;
  const cur = (el as HTMLInputElement).value;
  if (!cur) return false;
  const zh = localize(cur.trim());
  if (!zh) return false;
  (el as HTMLInputElement).value = zh;
  return true;
}

function translateElementAttrs(el: Element): boolean {
  let changed = translateInputValue(el);
  for (const name of ZH_ATTRS) {
    const cur = el.getAttribute(name);
    if (!cur) continue;
    const zh = localize(cur.trim());
    if (!zh) continue;
    el.setAttribute(name, zh);
    changed = true;
  }
  return changed;
}

function translateSubtree(root: Node): void {
  if (root.nodeType === 3 /* Text */) {
    translateTextNode(root as Text);
    return;
  }
  if (root.nodeType !== 1 /* Element */) {
    // DocumentFragment 等：继续向下
    if (root.nodeType === 11) {
      const kids = (root as DocumentFragment).childNodes;
      for (let i = 0; i < kids.length; i++) translateSubtree(kids[i]);
    }
    return;
  }
  const el = root as Element;
  translateElementAttrs(el);
  const walker = (el.ownerDocument as Document).createTreeWalker(
    el,
    NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT,
  );
  let n: Node | null = walker.currentNode;
  while (n) {
    if (n.nodeType === 3) translateTextNode(n as Text);
    else translateElementAttrs(n as Element);
    n = walker.nextNode();
  }
}

/**
 * 在（同源）文档中安装中文本地化。返回卸载函数。
 * 会在首屏做一次全量替换，并持续监听后续渲染（React 重渲染 / 懒加载）。
 */
export function installOpenReelZh(doc: Document, win: Window): () => void {
  const root = doc.documentElement;
  if (!root) return () => {};

  // 首屏全量（含 <head> 中的 <title>）
  translateSubtree(root);

  // 优先使用 iframe 自身 realm 的 MutationObserver，退化为宿主全局（同源可观测）。
  const MO = ((win as unknown as { MutationObserver?: typeof MutationObserver })
    .MutationObserver ?? MutationObserver) as typeof MutationObserver;

  const observer = new MO((mutations: MutationRecord[]) => {
    for (const m of mutations) {
      if (m.type === "characterData") {
        if (m.target) translateTextNode(m.target as Text);
      } else if (m.type === "attributes") {
        translateElementAttrs(m.target as Element);
      } else if (m.type === "childList") {
        m.addedNodes.forEach((n: Node) => translateSubtree(n));
      }
    }
  });

  // 监听整棵文档（而非仅 body）：这样 <head><title> 以及挂到 <html> 上的浮层同样被覆盖。
  // 脚本 / 样式 / 输入框内的文本由 shouldSkip 排除，不会被改动。
  observer.observe(root, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ZH_ATTRS,
  });

  return () => observer.disconnect();
}
